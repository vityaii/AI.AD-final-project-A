-- PostgreSQL 17+. Только новая пустая учебная БД. Повторный запуск завершится ошибкой.
BEGIN;
CREATE TABLE users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(50) NOT NULL UNIQUE CHECK (btrim(username) <> '')
);
CREATE TABLE projects (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL CHECK (btrim(name) <> '')
);
CREATE TABLE columns (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id integer NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
 name varchar(100) NOT NULL CHECK (btrim(name) <> ''),
 position integer NOT NULL CHECK (position >= 0),
 is_done boolean NOT NULL DEFAULT false,
 UNIQUE (project_id, id),
 UNIQUE (project_id, position)
);
CREATE TABLE tasks (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id integer NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
 column_id integer NOT NULL,
 user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 assignee_id integer CONSTRAINT tasks_assignee_fk REFERENCES users(id) ON DELETE SET NULL,
 task_number integer NOT NULL CHECK (task_number > 0),
 title varchar(100) NOT NULL CHECK (btrim(title) <> ''),
 text text NOT NULL DEFAULT '',
 priority varchar(6) NOT NULL DEFAULT 'medium'
   CONSTRAINT tasks_priority_check CHECK (priority IN ('low','medium','high')),
 due_date date,
 planned_duration_days integer CHECK (planned_duration_days > 0),
 CONSTRAINT tasks_project_number_unique UNIQUE (project_id, task_number),
 CONSTRAINT tasks_project_column_fk FOREIGN KEY (project_id, column_id)
   REFERENCES columns(project_id, id) ON DELETE RESTRICT
);
-- UNIQUE(project_id, task_number) уже индексирует задачи по проекту.
CREATE INDEX tasks_project_column_idx ON tasks(project_id, column_id);
CREATE INDEX tasks_assignee_idx ON tasks(assignee_id);
CREATE INDEX tasks_author_idx ON tasks(user_id);
CREATE INDEX tasks_due_date_idx ON tasks(due_date) WHERE due_date IS NOT NULL;
COMMENT ON COLUMN tasks.user_id IS 'Создатель задачи; не исполнитель';
COMMENT ON COLUMN tasks.due_date IS 'Последний допустимый календарный день; NULL — срок неизвестен';
COMMENT ON COLUMN tasks.planned_duration_days IS 'Плановая календарная длительность в днях, NULL — неизвестна';
COMMIT;
